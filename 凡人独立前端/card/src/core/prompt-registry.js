/**
 * 占位符填充：把 `{{名字}}` 换成真值。
 *
 * **这是整个流程唯一的组装方式**：提示词模板里永远保留占位符，
 * 数据在运行时填进去。不允许把资料硬拼在模板后面——
 * 那样模板就成了一段半成品，玩家改了也看不出资料从哪进。
 *
 * 规则：
 *   · 模板里有的占位符，值里有的就替换；值缺的写「无」
 *     （与原版 `|| '无'` 一致，模型看得见「这段是空的」）
 *   · 值里**没有**这个键，占位符原样保留。
 *     这样玩家写错占位符名时不会被静默清空，能自己发现。
 *   · 模板里没引用的数据不会出现在提示词里。
 *     玩家删掉某个占位符 = 他不要这段资料，这是他的选择。
 *
 * @param {string} template
 * @param {Record<string,string>} values 键含花括号，如 '{{年表材料}}'
 * @returns {string}
 */
export function fillTemplate(template, values) {
  const tpl = String(template == null ? '' : template);
  const map = values && typeof values === 'object' ? values : {};

  let out = tpl;
  for (const [token, raw] of Object.entries(map)) {
    if (!out.includes(token)) continue;
    const text = String(raw == null ? '' : raw).trim();
    out = out.split(token).join(text === '' ? '无' : text);
  }
  return out.trim();
}

/**
 * 一段提示词模板里声明了哪些占位符（去重，保持出现顺序）。
 *
 * 用途：面板上提示「这段可用哪些占位符」，以及
 * 测试里校验「模板声明了 {{X}}，实际组装时确实传了 X」。
 *
 * @param {string} template
 * @returns {string[]}
 */
export function extractTemplateVars(template) {
  const tpl = String(template == null ? '' : template);
  const found = [];
  for (const m of tpl.matchAll(/\{\{([^{}]+)\}\}/g)) {
    const token = `{{${m[1]}}}`;
    if (!found.includes(token)) found.push(token);
  }
  return found;
}

/**
 * 判断某段提示词的模板里是否引用了某个占位符。
 * @param {string} template
 * @param {string} token 形如 '{{年表材料}}'
 * @returns {boolean}
 */
export function templateUses(template, token) {
  return String(template == null ? '' : template).includes(String(token));
}

/**
 * 取某段提示词的最终生效文本。
 *
 * 覆盖为空 → 用默认。这与卡内 `imagePromptTemplateOverrides` 的约定一致。
 *
 * @param {string} key 注册表 ID
 * @param {object} [ctx] 默认生成函数的入参
 * @param {object} [overrides] 玩家覆盖表 { [key]: string }
 * @returns {string}
 */
export function resolvePrompt(key, ctx, overrides) {
  const entry = CE_PROMPT_REGISTRY[key];
  if (!entry) return '';

  const custom = String(
    overrides && overrides[key] != null ? overrides[key] : '',
  ).trim();
  if (custom) return custom;

  if (typeof entry.build !== 'function') {
    // build=null 的项由各自模块传入默认文本
    const fallback = ctx && ctx.defaultText;
    return String(fallback == null ? '' : fallback);
  }
  return String(entry.build(ctx || {}) || '');
}

/**
 * 判断某段提示词是否被玩家改过。
 * 面板上要能一眼看出来哪些是自定义的。
 *
 * @param {string} key
 * @param {object} [overrides]
 * @returns {boolean}
 */
export function isPromptOverridden(key, overrides) {
  return String(overrides && overrides[key] != null ? overrides[key] : '').trim().length > 0;
}

/**
 * 列出所有可编辑项，按分组组织好——面板直接照这个渲染。
 *
 * @param {object} [overrides]
 * @returns {Array<{id:string, label:string, desc:string, items:Array}>}
 */
export function listEditablePrompts(overrides) {
  return CE_PROMPT_GROUPS.map((group) => ({
    id: group.id,
    label: group.label,
    desc: group.desc,
    items: Object.values(CE_PROMPT_REGISTRY)
      .filter((entry) => entry.group === group.id)
      .map((entry) => ({
        key: entry.key,
        label: entry.label,
        desc: entry.desc,
        vars: entry.vars || [],
        overridden: isPromptOverridden(entry.key, overrides),
        custom: String(overrides && overrides[entry.key] != null ? overrides[entry.key] : ''),
      })),
  }));
}

/**
 * 恢复单段默：把覆盖删掉即可（约定是「空 = 用默认」）。
 *
 * @param {object} overrides
 * @param {string} key
 * @returns {object} 新的覆盖表
 */
export function resetPrompt(overrides, key) {
  const next = { ...(overrides || {}) };
  delete next[key];
  return next;
}

