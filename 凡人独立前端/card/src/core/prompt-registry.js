/**
 * 校验覆盖表里有没有不认识的 key（改名/删除后残留）。
 *
 * @param {object} overrides
 * @returns {string[]} 无主的 key
 */
export function findOrphanOverrides(overrides) {
  const known = new Set(Object.keys(CE_PROMPT_REGISTRY));
  return Object.keys(overrides || {}).filter((k) => !known.has(k));
}
